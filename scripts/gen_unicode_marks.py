#!/usr/bin/env python3
"""Write both speech chunkers' checked-in mark tables from ``unicodedata``.

Both frontends read generated tables from the repository, so upgrading a
Python interpreter or Rust dependency does not silently move speech cut
points. Regenerating both files is the explicit way to change the mark set.

The checked-in tables hold CPython 3.12's UCD 15.0.0 marks. Run this when the
repository deliberately moves its cut points to a newer Unicode version::

    python scripts/gen_unicode_marks.py

``test/modular/test_speech_chunking.py`` checks that the two generated tables
agree and, when run under the source UCD version, checks every code point
against ``unicodedata``. A different interpreter no longer changes chunking.
"""

from __future__ import annotations

import sys
import unicodedata
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
RUST_TABLE = ROOT / "rust/server/src/unicode_marks.rs"
PYTHON_TABLE = ROOT / "mstar/api_server/openai/unicode_marks.py"
PER_LINE = 4

HEADER = """\
// @generated by scripts/gen_unicode_marks.py. Do not edit.
//
// Checked-in category M code points as inclusive ranges, sorted and neither
// overlapping nor adjacent. Both frontends use these cut points regardless of
// their interpreter or dependency Unicode versions.
//
// Regenerate both tables with `python scripts/gen_unicode_marks.py` when
// deliberately changing speech cut points.
"""

PYTHON_HEADER = """\
# @generated by scripts/gen_unicode_marks.py. Do not edit.
# Category M code points used by both speech chunkers, independent of the
# running interpreter's Unicode version. Regenerate both tables together.
"""


def mark_ranges() -> list[tuple[int, int]]:
    """Every code point of category ``M*``, as inclusive ranges."""
    ranges: list[tuple[int, int]] = []
    for code in range(sys.maxunicode + 1):
        if not unicodedata.category(chr(code)).startswith("M"):
            continue
        if ranges and ranges[-1][1] == code - 1:
            ranges[-1] = (ranges[-1][0], code)
        else:
            ranges.append((code, code))
    return ranges


def render(ranges: list[tuple[int, int]], ucd_version: str) -> str:
    """The Rust source for ``ranges``."""
    pairs = [f"(0x{low:04x}, 0x{high:04x})," for low, high in ranges]
    lines = [
        "    " + " ".join(pairs[i:i + PER_LINE]).rstrip()
        for i in range(0, len(pairs), PER_LINE)
    ]
    total = sum(high - low + 1 for low, high in ranges)
    return (
        f"{HEADER}\n"
        f"// Source UCD {ucd_version}.\n"
        f"/// {total} code points in {len(ranges)} ranges.\n"
        "pub const MARK_RANGES: &[(u32, u32)] = &[\n" + "\n".join(lines) + "\n];\n"
    )


def render_python(ranges: list[tuple[int, int]], ucd_version: str) -> str:
    """The Python source for the same ranges and source UCD version."""
    pairs = [f"(0x{low:04x}, 0x{high:04x})," for low, high in ranges]
    lines = [
        "    " + " ".join(pairs[i:i + PER_LINE]).rstrip()
        for i in range(0, len(pairs), PER_LINE)
    ]
    return (
        f"{PYTHON_HEADER}\n"
        f'UCD_VERSION = "{ucd_version}"\n'
        "MARK_RANGES = (\n" + "\n".join(lines) + "\n)\n"
    )


def main() -> None:
    ranges = mark_ranges()
    RUST_TABLE.write_text(render(ranges, unicodedata.unidata_version))
    PYTHON_TABLE.write_text(render_python(ranges, unicodedata.unidata_version))
    total = sum(high - low + 1 for low, high in ranges)
    print(f"{RUST_TABLE}, {PYTHON_TABLE}: {total} code points in {len(ranges)} ranges "
          f"(UCD {unicodedata.unidata_version})")


if __name__ == "__main__":
    main()
