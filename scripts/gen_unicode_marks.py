#!/usr/bin/env python3
"""Write ``rust/server/src/unicode_marks.rs`` from this interpreter's ``unicodedata``.

The Rust frontend has to split text exactly where the Python one does, and
``speech_chunking`` asks whether a character is a combining mark
(``unicodedata.category(c).startswith("M")``) to decide a cut point. Rust's
``regex`` crate carries its own Unicode tables, which move with the crate and
not with CPython, so ``\\p{M}`` there answers for a different Unicode version
than ``unicodedata`` does here. The table this writes removes the question:
the Rust side reads the marks of the interpreter the Python frontend runs on.

The table holds the marks of the interpreter the repository tests on: CPython
3.12, which carries UCD 15.0.0, as does 3.13. Run this after a CPython upgrade
that moves the mark set (16.0.0 adds 51 of them, U+0897 among them)::

    python scripts/gen_unicode_marks.py

``test/modular/test_speech_chunking.py`` compares the checked-in table against
the running interpreter's ``unicodedata`` over every code point, so a table
that is not regenerated fails rather than quietly splitting text differently on
the two frontends. Regenerating from an interpreter with a different mark set
also moves the two cases pinned to U+0897, in ``speech_chunking.rs``.
"""

from __future__ import annotations

import sys
import unicodedata
from pathlib import Path

TABLE = Path(__file__).resolve().parents[1] / "rust/server/src/unicode_marks.rs"
PER_LINE = 4

HEADER = """\
// @generated by scripts/gen_unicode_marks.py. Do not edit.
//
// The code points CPython's `unicodedata` calls combining marks, as inclusive
// ranges, sorted and neither overlapping nor adjacent. `speech_chunking` reads
// them so that the Rust frontend cuts long text where the Python one does;
// `regex`'s `\\p{M}` carries the crate's own Unicode tables instead of the
// interpreter's, which is the same question asked of a different version.
//
// Regenerate with `python scripts/gen_unicode_marks.py` and say so in the
// commit: the cut points of text holding the affected code points move with it.
"""


def mark_ranges() -> list[tuple[int, int]]:
    """Every code point of category ``M*``, as inclusive ranges."""
    ranges: list[tuple[int, int]] = []
    for code in range(sys.maxunicode + 1):
        if not unicodedata.category(chr(code)).startswith("M"):
            continue
        if ranges and ranges[-1][1] == code - 1:
            ranges[-1] = (ranges[-1][0], code)
        else:
            ranges.append((code, code))
    return ranges


def render(ranges: list[tuple[int, int]]) -> str:
    """The Rust source for ``ranges``."""
    pairs = [f"(0x{low:04x}, 0x{high:04x})," for low, high in ranges]
    lines = [
        "    " + " ".join(pairs[i:i + PER_LINE]).rstrip()
        for i in range(0, len(pairs), PER_LINE)
    ]
    total = sum(high - low + 1 for low, high in ranges)
    return (
        f"{HEADER}\n"
        f"/// {total} code points in {len(ranges)} ranges.\n"
        "pub const MARK_RANGES: &[(u32, u32)] = &[\n" + "\n".join(lines) + "\n];\n"
    )


def main() -> None:
    ranges = mark_ranges()
    TABLE.write_text(render(ranges))
    total = sum(high - low + 1 for low, high in ranges)
    print(f"{TABLE}: {total} code points in {len(ranges)} ranges (UCD {unicodedata.unidata_version})")


if __name__ == "__main__":
    main()
