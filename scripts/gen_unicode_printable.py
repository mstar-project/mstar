#!/usr/bin/env python3
"""Write Rust's refusal-text printability table from this Python interpreter.

``str.isprintable`` changes when CPython updates its Unicode tables. Rust's
``regex`` crate has its own tables, so a category regex can disagree with the
Python frontend. Regenerate after upgrading the tested Python interpreter::

    python scripts/gen_unicode_printable.py

``test/rust/test_unicode_printable.py`` checks the table against the running
interpreter over every code point. The checked-in table is from the repository's
tested CPython 3.12, whose ``unicodedata`` version is 15.0.0.
"""

from __future__ import annotations

import sys
import unicodedata
from pathlib import Path

TABLE = Path(__file__).resolve().parents[1] / "rust/server/src/unicode_printable.rs"
PER_LINE = 4

HEADER = f"""\
// @generated by scripts/gen_unicode_printable.py. Do not edit.
//
// Code points for which CPython's `str.isprintable` is false, as inclusive,
// sorted, nonadjacent ranges. `media::py_repr` reads this table to quote a
// client's rejected value like the Python frontend does. Regenerate when the
// tested interpreter's Unicode tables change.
// Generated from CPython `str.isprintable` with UCD {unicodedata.unidata_version}.
"""


def unprintable_ranges() -> list[tuple[int, int]]:
    ranges: list[tuple[int, int]] = []
    for code in range(sys.maxunicode + 1):
        if chr(code).isprintable():
            continue
        if ranges and ranges[-1][1] == code - 1:
            ranges[-1] = (ranges[-1][0], code)
        else:
            ranges.append((code, code))
    return ranges


def render(ranges: list[tuple[int, int]]) -> str:
    pairs = [f"(0x{low:04x}, 0x{high:04x})," for low, high in ranges]
    lines = [
        "    " + " ".join(pairs[i:i + PER_LINE]).rstrip()
        for i in range(0, len(pairs), PER_LINE)
    ]
    total = sum(high - low + 1 for low, high in ranges)
    return (
        f"{HEADER}\n"
        f"/// {total} code points in {len(ranges)} ranges.\n"
        "pub const UNPRINTABLE_RANGES: &[(u32, u32)] = &[\n"
        + "\n".join(lines)
        + "\n];\n"
    )


def main() -> None:
    ranges = unprintable_ranges()
    TABLE.write_text(render(ranges))
    total = sum(high - low + 1 for low, high in ranges)
    print(f"{TABLE}: {total} code points in {len(ranges)} ranges (UCD {unicodedata.unidata_version})")


if __name__ == "__main__":
    main()
