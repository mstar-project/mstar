"""Orpheus SNAC streaming with the real SNAC 24 kHz weights.

Streams real Orpheus token streams (four utterances generated by
``canopylabs/orpheus-3b-0.1-ft``, in ``data/orpheus_tokens.safetensors``)
through the edge's chunk policy and ``SNACDecoderSubmodule``, and compares
the concatenated audio with one decode of each whole utterance.

SNAC's decoder adds random noise by design (``NoiseBlock``). It is switched
off here so the comparison measures the windowing alone: with it on, two
whole decodes of the same codes are only 24 to 32 dB apart.

The module never downloads weights: it skips unless ``hubertsiuzdak/snac_24khz``
is in a local Hugging Face cache. It runs on CPU in a few seconds.
"""

from __future__ import annotations

import os
from pathlib import Path
from types import SimpleNamespace

import pytest
import torch

HF_REPO = "hubertsiuzdak/snac_24khz"
TOKENS = Path(__file__).parent / "data" / "orpheus_tokens.safetensors"
HOP = 2048
HALF_WINDOW = 1200  # 50 ms either side of a chunk boundary


def _find_cached_snapshot() -> Path | None:
    repo_dir = f"models--{HF_REPO.replace('/', '--')}"
    roots = []
    if os.environ.get("HF_HUB_CACHE"):
        roots.append(Path(os.environ["HF_HUB_CACHE"]))
    if os.environ.get("HF_HOME"):
        roots.append(Path(os.environ["HF_HOME"]) / "hub")
    roots.append(Path.home() / ".cache" / "huggingface" / "hub")
    for root in roots:
        snapshots = root / repo_dir / "snapshots"
        if not snapshots.is_dir():
            continue
        for snapshot in snapshots.iterdir():
            if (snapshot / "config.json").is_file() and (snapshot / "pytorch_model.bin").is_file():
                return snapshot
    return None


pytest.importorskip("safetensors")
SNAPSHOT = _find_cached_snapshot()
if SNAPSHOT is None:
    pytest.skip(f"{HF_REPO} weights are not in the local Hugging Face cache", allow_module_level=True)

from safetensors.torch import load_file  # noqa: E402

from mstar.model.orpheus.components import snac as snac_module  # noqa: E402
from mstar.model.orpheus.components.snac import SNAC  # noqa: E402
from mstar.model.orpheus.config import OrpheusModelConfig  # noqa: E402
from mstar.model.orpheus.orpheus_model import OrpheusModel  # noqa: E402
from mstar.model.orpheus.submodules import SNACDecoderSubmodule  # noqa: E402
from mstar.model.submodule_base import InputMetadata, ModelInputsFromEngine  # noqa: E402
from mstar.streaming.stream_buffer import StreamBuffer  # noqa: E402


@pytest.fixture(scope="module")
def submodule():
    patch = pytest.MonkeyPatch()
    patch.setattr(snac_module.NoiseBlock, "forward", lambda self, x: x)
    device = "cuda" if torch.cuda.is_available() else "cpu"
    model = SNAC.from_pretrained(str(SNAPSHOT)).eval().to(device)
    yield SNACDecoderSubmodule(model, OrpheusModelConfig())
    patch.undo()


def _stream(submodule: SNACDecoderSubmodule, tokens: torch.Tensor) -> list[torch.Tensor]:
    """One token per LLM step through the edge's buffer; the audio of each chunk."""
    topology = OrpheusModel.get_partition_topology(SimpleNamespace(config=submodule.config))
    buffer = StreamBuffer(request_id="r", edge_name="new_token", from_partition="LLM",
                          policy=topology.connections[0].chunk_policy_factory())
    info = SimpleNamespace(request_id="r", rid_handle="r")
    chunks = []

    def drain():
        while buffer.has_chunk_ready():
            chunk = buffer.pop_chunk()
            meta = InputMetadata(stream_chunks={"new_token": chunk.info})
            engine = ModelInputsFromEngine(request_ids=["r"], per_request_info={},
                                           per_request_input_metadata={"r": meta}, captured=False)
            item = submodule.prepare_inputs("snac_chunk", info, {"new_token": [chunk.data["data"]]},
                                            input_metadata=meta, is_final_stream_chunk=chunk.is_final)
            packed = submodule.preprocess("snac_chunk", engine, [item])
            with torch.no_grad():
                out = submodule.forward_batched("snac_chunk", engine, **packed)
            submodule.postprocess("r", info, out["r"], inputs=item)
            chunks.append(out["r"]["audio_chunk"][0].reshape(-1).cpu())

    for i, token in enumerate(tokens):
        buffer.pre_read_register(f"t{i}")
        buffer.put(f"t{i}", token.view(1))
        drain()
    buffer.signal_done()
    drain()
    return chunks


def _whole(submodule: SNACDecoderSubmodule, tokens: torch.Tensor) -> torch.Tensor:
    frames = tokens.numel() // 7
    codes = ((tokens[: frames * 7] - submodule.config.custom_token_base_id - 10) % 4096).view(1, frames, 7)
    with torch.no_grad():
        audio = submodule.snac_model.decode(list(submodule._extract_snac_codes(codes)))
    return (audio.clamp(-1, 1) * 32767).to(torch.int16).reshape(-1).cpu()


def _snr(ref: torch.Tensor, x: torch.Tensor) -> float:
    ref, x = ref.double(), x.double()
    return float(10 * torch.log10(ref.pow(2).sum() / (ref - x).pow(2).sum().clamp_min(1e-20)))


@pytest.mark.parametrize("name", ["short", "question", "medium", "long"])
def test_stream_matches_whole_decode(submodule, name):
    device = next(submodule.snac_model.parameters()).device
    tokens = load_file(str(TOKENS))[name].long().to(device)
    chunks = _stream(submodule, tokens)
    stream, whole = torch.cat(chunks), _whole(submodule, tokens)
    # every whole frame, from the first to the last (the trailing EOS is not audio)
    assert stream.numel() == whole.numel() == (tokens.numel() // 7) * HOP
    # measured 62 to 72 dB on these four (the old 1-left / 2-right window: 25 to 28)
    assert _snr(whole, stream) > 55.0
    boundary = 0
    for chunk in chunks[:-1]:
        boundary += chunk.numel()
        lo, hi = max(boundary - HALF_WINDOW, 0), min(boundary + HALF_WINDOW, whole.numel())
        if chunk.numel() and whole[lo:hi].abs().max() > 0:
            # measured >= 44.9 dB; the old window dropped to 12.8 dB
            assert _snr(whole[lo:hi], stream[lo:hi]) > 35.0, f"boundary at sample {boundary}"
